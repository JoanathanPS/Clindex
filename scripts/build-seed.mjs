#!/usr/bin/env node
// Converts data/*.csv into packages/clinical/src/seed.ts so the engine can run
// in the browser (public demo) with exactly the data seeded into Supabase.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
function csv(file) {
  const text = readFileSync(join(ROOT, "data", file), "utf8").trim();
  const rows = [];
  for (const line of text.split(/\r?\n/)) {
    const out = []; let f = "", q = false;
    for (let i = 0; i < line.length; i++) {
      const c = line[i];
      if (q) { if (c === '"' && line[i + 1] === '"') { f += '"'; i++; } else if (c === '"') q = false; else f += c; }
      else if (c === '"') q = true; else if (c === ",") { out.push(f); f = ""; } else f += c;
    }
    out.push(f); rows.push(out);
  }
  const [h, ...body] = rows;
  return body.map((r) => Object.fromEntries(h.map((k, i) => [k, r[i] === "" ? null : r[i]])));
}
const rules = csv("drug_patient_risk_rules.csv").map((r) => ({ ...r, drug_name: r.drug_name.toLowerCase(), risk_level: r.risk_level.toLowerCase() }));
const interactions = csv("interactions_seed.csv").map((r) => ({ ...r, drug_a: r.drug_a.toLowerCase(), drug_b: r.drug_b.toLowerCase(), severity: r.severity.toLowerCase() }));
const mapping = csv("drug_mapping.csv").map((r) => ({ drug_name: r.drug_name, rxcui: r.rxcui, drug_class: r.drug_class }));
writeFileSync(join(ROOT, "packages/clinical/src/seed.ts"), `// GENERATED by scripts/build-seed.mjs from data/*.csv — do not edit by hand.
import type { ManualInteraction, ManualRule } from "./manual";

export const SEED_RULES: ManualRule[] = ${JSON.stringify(rules, null, 2)};

export const SEED_INTERACTIONS: ManualInteraction[] = ${JSON.stringify(interactions, null, 2)};

export const SEED_DRUGS: Array<{ drug_name: string; rxcui: string | null; drug_class: string | null }> = ${JSON.stringify(mapping, null, 2)};
`);
console.log(`seed: ${rules.length} rules, ${interactions.length} interactions, ${mapping.length} drugs`);
